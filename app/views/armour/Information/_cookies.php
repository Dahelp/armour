<p>Файлы cookie — небольшие фрагменты данных, которые сайт сохраняет в браузере пользователя. Они помогают поддерживать сеанс, корзину и выбранные настройки.</p>

<h2>Какие cookie использует сайт</h2>
<ul>
    <li><strong>Технические:</strong> сессия, защита форм и корректная работа сайта.</li>
    <li><strong>Функциональные:</strong> содержимое корзины, выбранная валюта и недавно просмотренные товары.</li>
    <li><strong>Аналитические и рекламные:</strong> в настоящий момент не используются. При их подключении сайт сначала запросит отдельное согласие.</li>
</ul>

<h2>Как управлять cookie</h2>
<p>Уведомление сайта информирует об использовании обязательных cookie и не имитирует выбор между отсутствующими категориями. Пользователь может удалить или запретить cookie в настройках браузера, но отключение технических cookie способно нарушить работу корзины, авторизации и форм.</p>

