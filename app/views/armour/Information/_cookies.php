<p>Файлы cookie — небольшие фрагменты данных, которые сайт сохраняет в браузере пользователя. Они помогают поддерживать сеанс, корзину и выбранные настройки.</p>

<h2>Какие cookie использует сайт</h2>
<ul>
    <li><strong>Технические:</strong> сессия, защита форм и корректная работа сайта.</li>
    <li><strong>Функциональные:</strong> содержимое корзины, выбранная валюта и недавно просмотренные товары.</li>
    <li><strong>Аналитические:</strong> могут применяться после подключения соответствующего сервиса и получения необходимого согласия для оценки посещаемости и улучшения сайта.</li>
</ul>

<h2>Как управлять cookie</h2>
<p>Пользователь может удалить или запретить cookie в настройках браузера. Отключение технических cookie способно нарушить работу корзины, авторизации и форм. Настройки аналитических cookie, если они используются, доступны в уведомлении сайта.</p>

